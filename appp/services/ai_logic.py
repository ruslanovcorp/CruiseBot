def generate_response(message):
    message = message.lower()

    if "цена" in message:
        return "Стоимость круизов начинается от 1200$ на человека."

    if "маршрут" in message:
        return "Мы предлагаем Средиземное море, Карибы и Азию."

    if "забронировать" in message:
        return "Пожалуйста, укажите желаемые даты и количество человек."

    return "Здравствуйте! Вас интересуют цены, маршруты или бронирование?"